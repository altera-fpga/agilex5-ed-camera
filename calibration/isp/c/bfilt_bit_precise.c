union float_view {
    float f;
    uint32_t u;
};

float to_tf32(float x) {
    union float_view fu;
    fu.f = x;
    fu.u &= TF32_MASK; 
    return fu.f;
}

float u2f(uint32_t x) {
    union float_view fu;
    fu.u = x;
    return fu.f;
}

float exp_lut(float x) {
    const uint32_t lut[] = EXPONENTIAL_LUT;
    union float_view fu;
    fu.f = fabs(x);
    if (fu.u < EXP_LUT_EXP_OFFSET) {
        return 1.0; // Underflow, exp(-0.0) = 1.0
    }
    fu.u -= EXP_LUT_EXP_OFFSET;
    if (fu.u > EXP_LUT_ADDR_MAX) {
        return 0.0; // Overflow, exp(-inf) = 0.0
    }
    // Lookup and convert to TF32
    return to_tf32(u2f(
        lut[fu.u >> EXP_LUT_ADDR_SHIFT] << FP19_TO_FP32_SHIFT
    ));
}

float reciprocal_lut(float x) {
    const uint32_t lut[] = RECIPROCAL_LUT;
    uint32_t tmp;
    union float_view fu;
    assert(x >= 1.0 && x <= 255);
    fu.f = x;
    tmp = lut[(fu.u & RECIP_LUT_ADDR_MASK) >> RECIP_LUT_ADDR_SHIFT];
    tmp <<= RECIP_LUT_DATA_SHIFT;
    tmp |= RECIP_LUT_DATA_MSBS;
    return u2f(tmp);
}

float intensity_range_lut(float x, double* user_data_ptr) {
    size_t i = x;
    if (BPS > 10) {
        i >>= BPS - 10; // Max LUT address size is 10 bits
    }
    // Lookup and convert to TF32
    return to_tf32(user_data_ptr[INTENSITY_RANGE_LUT_OFFSET + i]);
}

float spatial_distance_lut(int x, double* user_data_ptr) {
    // x must not be equal to RADIUS
    assert(x != RADIUS);
    size_t i = abs(x - RADIUS) - 1;
    // Lookup and convert to TF32
    return to_tf32(user_data_ptr[SPATIAL_DISTANCE_LUT_OFFSET + i]);
}

int bfilt(
    double*  buffer,
    intptr_t filter_size,
    double*  return_value,
    void*    user_data
) {
    double* user_data_ptr = (double*)user_data;
    float buffer_center;
    float pixel_acc;
    float weight_acc;
    float intensity_range_coeff;
    int idx = 0;

    float* buffer_tf32 = malloc((filter_size - 1) * sizeof(float));
    float* exponents = malloc((filter_size - 1) * sizeof(float));
    if (buffer_tf32 == NULL || exponents == NULL) {
        fprintf(stderr, "Error: Malloc failed");
        return -1;
    }

    buffer_center = to_tf32(buffer[RADIUS]);
    intensity_range_coeff = intensity_range_lut(buffer_center, user_data_ptr);
    for (int i = 0; i < filter_size; i++) {
        float dsp0, dsp1;
        if (i == RADIUS) {
            continue; // Skip calculation for the center element
        }
        buffer_tf32[idx] = to_tf32(buffer[i]);
        // DSP0 calculates difference of range scaled intensities
        dsp0 = to_tf32(intensity_range_coeff * buffer_center) -
            to_tf32(intensity_range_coeff * buffer_tf32[idx]);
        // DSP1 calculates square of DSP0 result plus spatial distance
        dsp1 = (dsp0 * dsp0) + spatial_distance_lut(i, user_data_ptr);
        // Exponential calculation, equivelant to: to_tf32(exp(-dsp1))
        exponents[idx] = exp_lut(dsp1);
        idx++;
    }

    weight_acc = 1.0;
    pixel_acc = buffer_center;
    for (int i = 0; i < RADIUS; i++) {
        // Corresponds to a DSP block in Agilex 5/7 devices
        weight_acc += to_tf32(exponents[2*i] + exponents[2*i+1]);
        // Corresponds to another DSP block in Agilex 5/7 devices
        pixel_acc += to_tf32(
            to_tf32(buffer_tf32[2*i] * exponents[2*i]) +
            to_tf32(buffer_tf32[2*i+1] * exponents[2*i+1])
        );
    }

    // Division by multiplying reciprocal, equivelant to: pixel_acc / weight_acc
    *return_value = pixel_acc * reciprocal_lut(weight_acc);
//     *return_value = pixel_acc / weight_acc;

    free(buffer_tf32);
    free(exponents);
    return 1;
}
